package org.example.repository.db;

import org.example.domain.Utilizator;
import org.example.exceptions.RepositoryException;
import org.example.repository.Repository;
import org.example.validation.Validator;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.sql.Timestamp;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;

/**
 * Users stored in the PostgreSQL table {@code users}
 * (id BIGINT GENERATED ALWAYS AS IDENTITY, first_name, last_name, username, created_at).
 * <p>
 * The id is generated by the database: save inserts the user without an id and sets on
 * the entity the id returned by the database (getGeneratedKeys).
 * Every method opens its own Connection, PreparedStatement and ResultSet in
 * try-with-resources, so they are closed also when an exception is thrown. All the values
 * are given as parameters (?) of a PreparedStatement, never concatenated into the SQL text,
 * so a name such as {@code '); DROP TABLE users; --} is saved as ordinary text.
 * {@link SQLException} is wrapped into {@link RepositoryException}.
 */
public class UtilizatorDbRepository implements Repository<Long, Utilizator> {
    private static final String SELECT_ONE =
            "SELECT id, first_name, last_name, username, created_at FROM users WHERE id = ?";
    private static final String SELECT_ALL =
            "SELECT id, first_name, last_name, username, created_at FROM users ORDER BY id";
    private static final String INSERT =
            "INSERT INTO users (first_name, last_name, username, created_at) VALUES (?, ?, ?, ?)";
    private static final String DELETE =
            "DELETE FROM users WHERE id = ? RETURNING id, first_name, last_name, username, created_at";
    private static final String UPDATE =
            "UPDATE users SET first_name = ?, last_name = ?, username = ?, created_at = ? WHERE id = ?";

    private final Validator<Utilizator> validator;
    private final String url;
    private final String user;
    private final String password;

    /**
     * Creates the repository. No connection is opened here: every operation opens its
     * own connection, so the application starts also when the database server is stopped.
     *
     * @param validator the validator for the users, used before save and update
     * @param url the JDBC url of the database (db.url)
     * @param user the database user (db.user)
     * @param password the database password (db.password)
     */
    public UtilizatorDbRepository(Validator<Utilizator> validator, String url, String user, String password) {
        this.validator = validator;
        this.url = url;
        this.user = user;
        this.password = password;
    }

    /**
     * @return a new connection to the database; the caller closes it
     * @throws SQLException if the connection cannot be opened (e.g. server stopped)
     */
    private Connection getConnection() throws SQLException {
        return DriverManager.getConnection(url, user, password);
    }

    /**
     * Builds a user from the current row of the result set.
     *
     * @param rs a result set positioned on a row of users
     * @return the user from the row
     * @throws SQLException if a column cannot be read
     */
    private static Utilizator extract(ResultSet rs) throws SQLException {
        return new Utilizator(rs.getLong("id"), rs.getString("username"), rs.getString("first_name"),
                rs.getString("last_name"), rs.getTimestamp("created_at").toLocalDateTime());
    }

    /**
     * Sets the parameters first_name, last_name, username, created_at (positions 1-4).
     *
     * @param ps the statement for INSERT or UPDATE
     * @param u the user whose fields are written
     * @throws SQLException if a parameter cannot be set
     */
    private static void setFields(PreparedStatement ps, Utilizator u) throws SQLException {
        ps.setString(1, u.getFirstName());
        ps.setString(2, u.getLastName());
        ps.setString(3, u.getUsername());
        ps.setTimestamp(4, Timestamp.valueOf(u.getCreatedAt()));
    }

    /**
     * {@inheritDoc}
     *
     * @param id the id of the user, must not be null
     * @return the user, or an empty Optional if there is no row with this id
     * @throws IllegalArgumentException if id is null
     * @throws RepositoryException if the database cannot be queried
     */
    @Override
    public Optional<Utilizator> findOne(Long id) {
        if (id == null) throw new IllegalArgumentException("Id-ul nu poate fi null!");
        try (Connection connection = getConnection();
             PreparedStatement ps = connection.prepareStatement(SELECT_ONE)) {
            ps.setLong(1, id);
            try (ResultSet rs = ps.executeQuery()) {
                return rs.next() ? Optional.of(extract(rs)) : Optional.empty();
            }
        } catch (SQLException e) {
            throw SqlErrors.wrap("cautarea utilizatorului cu id-ul " + id, e);
        }
    }

    /**
     * {@inheritDoc}
     *
     * @return all the users, ordered by id
     * @throws RepositoryException if the database cannot be queried
     */
    @Override
    public Iterable<Utilizator> findAll() {
        List<Utilizator> users = new ArrayList<>();
        try (Connection connection = getConnection();
             PreparedStatement ps = connection.prepareStatement(SELECT_ALL);
             ResultSet rs = ps.executeQuery()) {
            // ResultSet nu are stream(): se parcurge rand cu rand
            while (rs.next()) users.add(extract(rs));
            return users;
        } catch (SQLException e) {
            throw SqlErrors.wrap("citirea utilizatorilor", e);
        }
    }

    /**
     * Inserts the user; the database generates the id, which is then set on {@code entity}.
     *
     * @param entity the new user, without an id; must not be null
     * @return always an empty Optional: the id is new, so it cannot already exist
     * @throws IllegalArgumentException if entity is null or already has an id
     * @throws org.example.exceptions.ValidationException if the user is not valid
     * @throws RepositoryException if the insert fails (e.g. database stopped, username
     *         already used - UNIQUE constraint)
     */
    @Override
    public Optional<Utilizator> save(Utilizator entity) {
        if (entity == null) throw new IllegalArgumentException("Entitatea nu poate fi null!");
        if (entity.getId() != null)
            throw new IllegalArgumentException("Id-ul utilizatorului il genereaza baza de date!");
        validator.validate(entity);
        try (Connection connection = getConnection();
             PreparedStatement ps = connection.prepareStatement(INSERT, Statement.RETURN_GENERATED_KEYS)) {
            setFields(ps, entity);
            ps.executeUpdate();
            try (ResultSet keys = ps.getGeneratedKeys()) {
                if (!keys.next())
                    throw new RepositoryException("Baza de date nu a intors id-ul generat pentru "
                            + entity.getUsername());
                entity.setId(keys.getLong("id")); // id-ul generat de baza de date
            }
            return Optional.empty();
        } catch (SQLException e) {
            throw SqlErrors.wrap("salvarea utilizatorului " + entity.getUsername(), e);
        }
    }

    /**
     * Deletes the user. DELETE ... RETURNING gives back the deleted row in the same
     * statement, so no separate SELECT is needed. His friendships are deleted by the
     * database (ON DELETE CASCADE).
     *
     * @param id the id of the user, must not be null
     * @return the deleted user, or an empty Optional if there is no row with this id
     * @throws IllegalArgumentException if id is null
     * @throws RepositoryException if the delete fails
     */
    @Override
    public Optional<Utilizator> delete(Long id) {
        if (id == null) throw new IllegalArgumentException("Id-ul nu poate fi null!");
        try (Connection connection = getConnection();
             PreparedStatement ps = connection.prepareStatement(DELETE)) {
            ps.setLong(1, id);
            try (ResultSet rs = ps.executeQuery()) {
                return rs.next() ? Optional.of(extract(rs)) : Optional.empty();
            }
        } catch (SQLException e) {
            throw SqlErrors.wrap("stergerea utilizatorului cu id-ul " + id, e);
        }
    }

    /**
     * Updates the row with the id of {@code entity}. executeUpdate() returns the number of
     * changed rows: 0 means there is no user with this id.
     *
     * @param entity the new version of the user, must not be null
     * @return an empty Optional if the row was updated, or an Optional with {@code entity}
     *         if there is no user with its id
     * @throws IllegalArgumentException if entity or its id is null
     * @throws org.example.exceptions.ValidationException if the user is not valid
     * @throws RepositoryException if the update fails (e.g. username already used)
     */
    @Override
    public Optional<Utilizator> update(Utilizator entity) {
        if (entity == null) throw new IllegalArgumentException("Entitatea nu poate fi null!");
        if (entity.getId() == null) throw new IllegalArgumentException("Id-ul nu poate fi null!");
        validator.validate(entity);
        try (Connection connection = getConnection();
             PreparedStatement ps = connection.prepareStatement(UPDATE)) {
            setFields(ps, entity);
            ps.setLong(5, entity.getId());
            int rows = ps.executeUpdate();
            return rows == 0 ? Optional.of(entity) : Optional.empty();
        } catch (SQLException e) {
            throw SqlErrors.wrap("modificarea utilizatorului cu id-ul " + entity.getId(), e);
        }
    }
}
